def compare_global_vs_cohort_sigmoid_rps(
    df: pd.DataFrame,
    skill_col: str = "category_assessment",
    score_col: str = "score",
    cohort_col: str = "cohort",
    age_group_col: str = "age_group",
    gender_col: str = "gender_clean",
    timestamp_col: str = "timestamp",
    player_id_col: Optional[str] = None,
    span_percentile: float = 0.75,
    min_cohort_n: int = 30,
    skill_type_map: Optional[Dict[str, str]] = None,
    good_direction_map: Optional[Dict[str, str]] = None,
    clip_scores: bool = True,
) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame, Dict[str, pd.DataFrame]]:
    """
    Calculate global and cohort-based RPS with age-group fallback for small cohorts.

    Small sample logic:
    1. If assessment + age + gender cohort has n >= min_cohort_n, use that cohort.
    2. If assessment + age + gender cohort has n < min_cohort_n, drop gender and use
       the same age group distribution for that assessment.
    3. If the age-group distribution is unavailable or invalid, use global as a safety fallback.
    """
    config = RPSConfig(
        span_percentile=span_percentile,
        min_cohort_n=min_cohort_n,
        clip_scores=clip_scores,
    )

    data = df.copy()

    required_cols = [
        skill_col,
        score_col,
        cohort_col,
        age_group_col,
        gender_col,
        timestamp_col,
    ]

    if player_id_col is not None:
        required_cols.append(player_id_col)
        player_cols = [player_id_col]
    else:
        required_cols.extend(["first_name", "last_name"])
        player_cols = ["first_name", "last_name", gender_col, age_group_col]

    _validate_columns(data, required_cols)

    data[score_col] = pd.to_numeric(data[score_col], errors="coerce")
    data[timestamp_col] = pd.to_datetime(data[timestamp_col], errors="coerce")

    data = data.dropna(
        subset=[skill_col, score_col, cohort_col, age_group_col, gender_col, timestamp_col]
    ).copy()

    if skill_type_map is None:
        skill_type_map = build_skill_type_map()

    if good_direction_map is None:
        good_direction_map = build_good_direction_map()

    # --------------------------------------------------------
    # Prepare modeling score
    # --------------------------------------------------------
    data["skill_type"] = data[skill_col].map(skill_type_map).fillna("Normal")
    data["good_direction"] = data[skill_col].map(good_direction_map).fillna("Hi")

    data["score_model"] = np.where(
        data["skill_type"].eq("Log"),
        data[score_col].apply(_safe_log),
        data[score_col],
    )

    data = data.dropna(subset=["score_model"]).copy()

    data["score_oriented"] = np.where(
        data["good_direction"].eq("Lo"),
        -data["score_model"],
        data["score_model"],
    )

    # --------------------------------------------------------
    # Build benchmark parameter tables
    # --------------------------------------------------------
    global_params = _build_global_params(data, skill_col, config.span_percentile)
    cohort_params = _build_cohort_params(data, skill_col, cohort_col, config.span_percentile)
    age_group_params = _build_age_group_params(
        data, skill_col, age_group_col, config.span_percentile
    )

    # --------------------------------------------------------
    # Merge benchmark parameters
    # --------------------------------------------------------
    result_df = data.merge(
        global_params[[skill_col, "global_n", "global_mid", "global_span"]],
        on=skill_col,
        how="left",
    )

    result_df = result_df.merge(
        cohort_params[
            [
                skill_col,
                cohort_col,
                "cohort_n",
                "cohort_mid",
                "cohort_span",
                "cohort_p25",
                "cohort_p75",
            ]
        ],
        on=[skill_col, cohort_col],
        how="left",
    )

    result_df = result_df.merge(
        age_group_params[
            [
                skill_col,
                age_group_col,
                "age_group_n",
                "age_group_mid",
                "age_group_span",
                "age_group_p25",
                "age_group_p75",
            ]
        ],
        on=[skill_col, age_group_col],
        how="left",
    )

    # --------------------------------------------------------
    # Select final benchmark source
    # --------------------------------------------------------
    result_df["cohort_is_small"] = result_df["cohort_n"] < config.min_cohort_n

    use_age_gender = result_df["cohort_n"] >= config.min_cohort_n

    result_df["rps_benchmark_source"] = np.where(
        use_age_gender,
        "age_gender_cohort",
        "same_age_group_gender_combined",
    )

    result_df["rps_mid"] = np.where(
        use_age_gender,
        result_df["cohort_mid"],
        result_df["age_group_mid"],
    )

    result_df["rps_span"] = np.where(
        use_age_gender,
        result_df["cohort_span"],
        result_df["age_group_span"],
    )

    invalid_final_benchmark = (
        result_df["rps_mid"].isna()
        | result_df["rps_span"].isna()
        | (result_df["rps_mid"] == result_df["rps_span"])
    )

    result_df.loc[invalid_final_benchmark, "rps_benchmark_source"] = "global_fallback"
    result_df.loc[invalid_final_benchmark, "rps_mid"] = result_df.loc[
        invalid_final_benchmark, "global_mid"
    ]
    result_df.loc[invalid_final_benchmark, "rps_span"] = result_df.loc[
        invalid_final_benchmark, "global_span"
    ]

    # --------------------------------------------------------
    # Calculate attempt-level RPS
    # --------------------------------------------------------
    result_df["rps_global_sigmoid"] = result_df.apply(
        lambda row: _calculate_sigmoid_rps(
            row["score_oriented"], row["global_mid"], row["global_span"], config
        ),
        axis=1,
    )

    result_df["rps_cohort_sigmoid"] = result_df.apply(
        lambda row: _calculate_sigmoid_rps(
            row["score_oriented"], row["rps_mid"], row["rps_span"], config
        ),
        axis=1,
    )

    result_df["rps_difference"] = (
        result_df["rps_cohort_sigmoid"] - result_df["rps_global_sigmoid"]
    )
    result_df["abs_rps_difference"] = result_df["rps_difference"].abs()

    # --------------------------------------------------------
    # Calculate recency-weighted assessment-level RPS
    # --------------------------------------------------------
    result_df = result_df.sort_values(
        player_cols + [skill_col, timestamp_col],
        ascending=[True] * (len(player_cols) + 1) + [False],
    ).copy()

    result_df["attempt_count"] = result_df.groupby(player_cols + [skill_col])[
        skill_col
    ].transform("size")

    result_df["attempt_recency_rank"] = (
        result_df.groupby(player_cols + [skill_col]).cumcount() + 1
    )

    result_df["use_for_overall_rps"] = result_df["attempt_recency_rank"] <= 3

    result_df["attempt_weight"] = result_df.apply(
        lambda row: _assign_attempt_weight(
            int(row["attempt_count"]), int(row["attempt_recency_rank"])
        ),
        axis=1,
    )

    result_df["weighted_global_rps"] = (
        result_df["rps_global_sigmoid"] * result_df["attempt_weight"]
    )
    result_df["weighted_cohort_rps"] = (
        result_df["rps_cohort_sigmoid"] * result_df["attempt_weight"]
    )

    player_assessment_rps = (
        result_df[result_df["use_for_overall_rps"]]
        .groupby(player_cols + [skill_col], as_index=False)
        .agg(
            assessment_global_rps=("weighted_global_rps", "sum"),
            assessment_cohort_rps=("weighted_cohort_rps", "sum"),
            attempts_used_for_rps=("attempt_recency_rank", "max"),
            total_attempts=("attempt_count", "max"),
            most_recent_timestamp=(timestamp_col, "max"),
            benchmark_source=("rps_benchmark_source", "first"),
            cohort_n=("cohort_n", "first"),
            age_group_n=("age_group_n", "first"),
        )
    )

    # --------------------------------------------------------
    # Calculate overall player RPS
    # --------------------------------------------------------
    overall_player_rps = (
        player_assessment_rps.groupby(player_cols, as_index=False)
        .agg(
            overall_global_rps=("assessment_global_rps", "mean"),
            overall_cohort_rps=("assessment_cohort_rps", "mean"),
            number_of_assessments=(skill_col, "nunique"),
        )
    )

    overall_player_rps["overall_rps_difference"] = (
        overall_player_rps["overall_cohort_rps"]
        - overall_player_rps["overall_global_rps"]
    )

    diagnostics = _build_diagnostics(
        result_df=result_df,
        cohort_params=cohort_params,
        age_group_params=age_group_params,
        player_assessment_rps=player_assessment_rps,
        overall_player_rps=overall_player_rps,
        skill_col=skill_col,
        score_col=score_col,
        cohort_col=cohort_col,
        age_group_col=age_group_col,
        gender_col=gender_col,
        timestamp_col=timestamp_col,
        player_cols=player_cols,
    )

    return result_df, global_params, cohort_params, age_group_params, diagnostics


