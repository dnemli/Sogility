@dataclass(frozen=True)
class RPSConfig:
    """Configuration for the RPS scoring system."""

    span_percentile: float = 0.75
    min_cohort_n: int = 30
    s_span: float = 1.0986
    rps_min: float = 30.0
    rps_max: float = 99.0
    clip_scores: bool = True

    @property
    def rps_range(self) -> float:
        return self.rps_max - self.rps_min


