def build_skill_type_map(log_assessments: Optional[set] = None) -> Dict[str, str]:
    """
    Build skill type map.
    "Log" assessments are log-transformed inside the scoring function.
    All others default to "Normal".
    """
    if log_assessments is None:
        log_assessments = LOG_ASSESSMENTS

    return {assessment: "Log" for assessment in log_assessments}


def build_good_direction_map(lower_is_better_assessments: Optional[set] = None) -> Dict[str, str]:
    """
    Build direction map.
    "Lo" means lower raw score is better.
    All others default to "Hi".
    """
    if lower_is_better_assessments is None:
        lower_is_better_assessments = LOWER_IS_BETTER_ASSESSMENTS

    return {assessment: "Lo" for assessment in lower_is_better_assessments}


