def load_training_data(file_name: str = "training_session.csv") -> pd.DataFrame:
    """
    Load raw Sogility training session data with no header.
    """
    df = pd.read_csv(file_name, header=None)

    if df.shape[1] != len(RAW_COLUMNS):
        raise ValueError(
            f"Expected {len(RAW_COLUMNS)} columns, but found {df.shape[1]} columns."
        )

    df.columns = RAW_COLUMNS
    return df


def preprocess_training_data(df: pd.DataFrame) -> pd.DataFrame:
    """
    Clean raw training data and create modeling columns:
    - category_assessment
    - age_group
    - gender_clean
    - cohort
    - higher_is_better
    """
    data = df.copy()

    required_cols = RAW_COLUMNS
    _validate_columns(data, required_cols)

    data["score"] = pd.to_numeric(data["score"], errors="coerce")
    data["timestamp"] = pd.to_datetime(data["timestamp"], errors="coerce")

    text_cols = [
        "first_name",
        "last_name",
        "gender",
        "col_d",
        "category",
        "assessment",
    ]

    for col in text_cols:
        data[col] = data[col].astype(str).str.strip()

    data["category_assessment"] = data["category"] + " " + data["assessment"]
    data["age_group"] = data["col_d"].map(AGE_GROUP_MAP)
    data["gender_clean"] = data["gender"].str.upper().str[0]

    data = data[
        data["score"].notna()
        & data["timestamp"].notna()
        & data["age_group"].notna()
        & data["gender_clean"].isin(["M", "F"])
    ].copy()

    data["age_group"] = data["age_group"].astype(int)
    data["cohort"] = data["age_group"].astype(str) + "_" + data["gender_clean"]
    data["higher_is_better"] = ~data["category_assessment"].isin(
        LOWER_IS_BETTER_ASSESSMENTS
    )

    return data.reset_index(drop=True)


