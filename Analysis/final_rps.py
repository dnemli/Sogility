def _validate_columns(df: pd.DataFrame, required_cols: List[str]) -> None:
    """Raise a clear error if required columns are missing."""
    missing_cols = [col for col in required_cols if col not in df.columns]

    if missing_cols:
        raise ValueError(f"Missing required column(s): {missing_cols}")


def _safe_log(x: float) -> float:
    """Natural log with protection against zero, negative, and missing values."""
    if pd.isna(x) or x <= 0:
        return np.nan
    return float(np.log(x))


def _sigmoid(z: float) -> float:
    """Numerically stable enough sigmoid for this scoring use case."""
    return float(1 / (1 + np.exp(-z)))


def _calculate_sigmoid_rps(
    x: float,
    mid: float,
    span: float,
    config: RPSConfig,
) -> float:
    """
    Calculate RPS using:
        RPS = 30 + 69 * S(x)

    where:
        S(x) = 1 / (1 + exp(-z))
        z = S_SPAN * ((x - mid) / abs(span - mid))
    """
    denom = abs(span - mid)

    if pd.isna(x) or pd.isna(mid) or pd.isna(span) or denom == 0:
        return np.nan

    z = config.s_span * ((x - mid) / denom)
    score = config.rps_min + config.rps_range * _sigmoid(z)

    if config.clip_scores:
        score = np.clip(score, config.rps_min, config.rps_max)

    return float(score)


def _assign_attempt_weight(attempt_count: int, recency_rank: int) -> float:
    """
    Recency weighting for attempts within the same player and assessment.

    1 attempt:
        rank 1 = 1.00
    2 attempts:
        rank 1 = 2/3, rank 2 = 1/3
    3+ attempts:
        rank 1 = 0.50, rank 2 = 0.30, rank 3 = 0.20
        older attempts = 0
    """
    if recency_rank > 3:
        return 0.0

    if attempt_count == 1:
        return 1.0

    if attempt_count == 2:
        return 2 / 3 if recency_rank == 1 else 1 / 3

    if recency_rank == 1:
        return 0.50
    if recency_rank == 2:
        return 0.30
    if recency_rank == 3:
        return 0.20

    return 0.0


