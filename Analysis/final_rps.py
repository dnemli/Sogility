"""
final_rps.py (replaces Analysis/sigmoid_cohort.py for this repo).

Structured RPS scoring pipeline for Sogility assessment data.

Core scoring requirements
-------------------------
1. Final RPS range: 30 to 99
2. Formula: RPS = 30 + 69 * S(x)
3. Uses 75% span and S_SPAN = 1.0986
4. Lower-is-better assessments are direction-adjusted
5. Log-type assessments are log-transformed inside the scoring function
6. Small age + gender cohorts are handled by dropping gender and using same age group
7. Overall RPS uses recency-weighted attempts:
   - 1 attempt: 100%
   - 2 attempts: most recent 2/3, older 1/3
   - 3+ attempts: most recent 0.50, second 0.30, third 0.20

Important
---------
Do not log-transform score before calling the RPS function.
Do not reduce the input to most recent attempt only. The function needs full history
for recency-weighted overall RPS.
"""

