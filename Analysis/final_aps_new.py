def load_training_data(file_name: str, raw_columns: List[str]) -> pd.DataFrame:
    """Load raw training session data and assign expected columns."""
    df = pd.read_csv(file_name, header=None)

    if df.shape[1] != len(raw_columns):
        raise ValueError(
            f"Expected {len(raw_columns)} columns, but found {df.shape[1]} columns."
        )

    df.columns = raw_columns
    return df


def clean_basic_columns(df: pd.DataFrame) -> pd.DataFrame:
    """Clean text columns, convert score and timestamp, and create category_assessment."""
    data = df.copy()

    data["score"] = pd.to_numeric(data["score"], errors="coerce")
    data["timestamp"] = pd.to_datetime(data["timestamp"], errors="coerce")

    text_cols = ["first_name", "last_name", "gender", "col_d", "category", "assessment"]
    for col in text_cols:
        data[col] = data[col].astype(str).str.strip()

    data["category_assessment"] = data["category"] + " " + data["assessment"]

    data = data.dropna(subset=["score", "timestamp", "category_assessment"]).copy()
    return data


def add_cohort_fields(df: pd.DataFrame, config: APSConfig) -> pd.DataFrame:
    """Create age_group, gender_clean, and cohort columns."""
    data = df.copy()

    data["age_group"] = data["col_d"].map(config.age_map)
    data["gender_clean"] = data["gender"].str.upper().str[0]

    data = data[
        data["age_group"].notna()
        & data["gender_clean"].isin(["M", "F"])
    ].copy()

    data["age_group"] = data["age_group"].astype("Int64")
    data["cohort"] = data["age_group"].astype(str) + "_" + data["gender_clean"]

    return data


def add_score_metadata(df: pd.DataFrame, config: APSConfig) -> pd.DataFrame:
    """Add higher_is_better and apply log transformation for configured assessments."""
    data = df.copy()

    data["higher_is_better"] = (
        data["category_assessment"]
        .map(config.higher_is_better_map)
        .fillna(True)
    )

    log_mask = data["category_assessment"].isin(config.log_transform_assessments)
    positive_mask = data["score"] > 0

    data.loc[log_mask & positive_mask, "score"] = np.log(
        pd.to_numeric(data.loc[log_mask & positive_mask, "score"], errors="coerce")
    )

    data.loc[log_mask & ~positive_mask, "score"] = np.nan
    data = data.dropna(subset=["score"]).copy()

    return data


def preprocess_training_data(df: pd.DataFrame, config: APSConfig) -> pd.DataFrame:
    """Run the full preprocessing pipeline."""
    data = clean_basic_columns(df)
    data = add_cohort_fields(data, config)
    data = add_score_metadata(data, config)
    return data


