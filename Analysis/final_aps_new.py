def calculate_attempt_aps(scoring_df: pd.DataFrame) -> pd.DataFrame:
    """Calculate APS and attempt-level APS band for each raw attempt."""
    data = scoring_df.copy()

    data["APS"] = data.apply(
        lambda row: aps_from_benchmarks(
            score=row["score"],
            q30=row["q30"],
            q50=row["q50"],
            q70=row["q70"],
            q90=row["q90"],
            higher_is_better=row["higher_is_better"],
        ),
        axis=1,
    )

    data["APS_band_raw_attempt"] = data["APS"].apply(assign_aps_band)
    return data


def calculate_assessment_scores(
    scoring_df: pd.DataFrame,
    player_cols: List[str],
) -> pd.DataFrame:
    """Calculate recency-weighted APS for each player-assessment."""
    valid_scores = (
        scoring_df.dropna(subset=["APS", "aps_category", "timestamp"])
        .query("aps_category != 'Unmapped'")
        .copy()
    )

    assessment_recent_scores = (
        valid_scores.groupby(
            player_cols + ["aps_category", "category_assessment"],
            as_index=False,
        )
        .apply(weighted_recent_assessment_score)
        .reset_index(drop=True)
    )

    assessment_recent_scores["weighted_assessment_aps"] = (
        assessment_recent_scores["weighted_assessment_aps"].round(1)
    )

    return assessment_recent_scores


def calculate_category_scores(
    assessment_recent_scores: pd.DataFrame,
    player_cols: List[str],
) -> pd.DataFrame:
    """Average weighted assessment APS scores into APS parent categories."""
    category_scores = (
        assessment_recent_scores.groupby(player_cols + ["aps_category"], as_index=False)
        .agg(
            category_aps_score=("weighted_assessment_aps", "mean"),
            n_assessments_used=("category_assessment", "nunique"),
            assessments_used=(
                "category_assessment",
                lambda x: ", ".join(sorted(x.dropna().unique())),
            ),
        )
    )

    category_scores["category_aps_score"] = category_scores["category_aps_score"].round(1)
    category_scores["category_aps_band"] = category_scores["category_aps_score"].apply(assign_aps_band)

    return category_scores


def calculate_final_aps(
    category_scores: pd.DataFrame,
    player_cols: List[str],
) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """Calculate final overall APS and dashboard-friendly wide table."""
    final_aps = (
        category_scores.groupby(player_cols, as_index=False)
        .agg(
            final_aps_score=("category_aps_score", "mean"),
            n_categories_used=("aps_category", "nunique"),
        )
    )

    final_aps["final_aps_score"] = final_aps["final_aps_score"].round(1)
    final_aps["final_aps_band"] = final_aps["final_aps_score"].apply(assign_aps_band)

    category_scores_wide = category_scores.pivot_table(
        index=player_cols,
        columns="aps_category",
        values="category_aps_score",
        aggfunc="mean",
    ).reset_index()

    final_dashboard_scores = final_aps.merge(
        category_scores_wide,
        on=player_cols,
        how="left",
    )

    return final_aps, final_dashboard_scores


