def get_player_cols(df: pd.DataFrame) -> List[str]:
    """Use athlete_id when available, otherwise fall back to name, gender, and age group."""
    if "athlete_id" in df.columns:
        return ["athlete_id"]
    return ["first_name", "last_name", "gender_clean", "age_group"]


def map_assessment_category(assessment: object) -> str:
    """Map each assessment to one APS parent category."""
    if pd.isna(assessment):
        return "Unmapped"

    a = str(assessment).lower()

    if "circuit" in a:
        return "Dribbling"

    if "icon" in a:
        return "Passing"

    if (
        "tech touch" in a
        or "techtouch" in a
        or "1st touch" in a
        or "one touch" in a
    ):
        return "First Touch"

    if (
        "5-10-5" in a
        or "shuttle" in a
        or "sprint" in a
        or "10yd" in a
        or "10 yd" in a
        or "10yrd" in a
        or "10 yrd" in a
        or "dash" in a
    ):
        return "Agility"

    if (
        "go 360" in a
        or "scan" in a
        or "react" in a
        or "reaction" in a
        or "large to small" in a
        or "small to large" in a
        or "balance" in a
        or "vision wall" in a
        or "roxpro" in a
        or "reflection edge" in a
    ):
        return "Vision"

    return "Unmapped"


def interpolate_score(x: float, x0: float, x1: float, y0: float, y1: float) -> float:
    """Linearly interpolate y for x between two benchmark anchors."""
    if pd.isna(x0) or pd.isna(x1) or x1 == x0:
        return np.nan
    return y0 + (x - x0) * (y1 - y0) / (x1 - x0)


def aps_from_benchmarks(
    score: float,
    q30: float,
    q50: float,
    q70: float,
    q90: float,
    higher_is_better: bool = True,
) -> float:
    """
    Convert raw score into APS using benchmark anchors.

    Anchors:
        q30 -> 30
        q50 -> 50
        q70 -> 70
        q90 -> 90
    """
    if any(pd.isna(v) for v in [score, q30, q50, q70, q90]):
        return np.nan

    if not higher_is_better:
        score = -score
        q30, q50, q70, q90 = sorted([-q90, -q70, -q50, -q30])

    if score <= q30:
        aps = interpolate_score(score, q30 - (q50 - q30), q30, 0, 30)
    elif score <= q50:
        aps = interpolate_score(score, q30, q50, 30, 50)
    elif score <= q70:
        aps = interpolate_score(score, q50, q70, 50, 70)
    elif score <= q90:
        aps = interpolate_score(score, q70, q90, 70, 90)
    else:
        aps = interpolate_score(score, q90, q90 + (q90 - q70), 90, 100)

    return float(np.clip(aps, 0, 100))


def assign_aps_band(score: float) -> object:
    """Convert APS score into a performance band."""
    if pd.isna(score):
        return np.nan
    if score < 30:
        return "Foundation"
    if score < 50:
        return "Developing"
    if score < 70:
        return "Approaching"
    if score < 90:
        return "Strong"
    return "Elite"


def get_recent_weights(n: int) -> List[float]:
    """Return recency weights for the most recent one, two, or three attempts."""
    if n == 1:
        return [1.0]
    if n == 2:
        return [2 / 3, 1 / 3]
    return [0.5, 0.3, 0.2]


def weighted_recent_assessment_score(group: pd.DataFrame) -> pd.Series:
    """Calculate weighted APS for one player and one assessment."""
    recent = group.sort_values("timestamp", ascending=False).head(3).copy()
    weights = get_recent_weights(len(recent))

    recent["recent_weight"] = weights
    weighted_score = np.average(recent["APS"], weights=recent["recent_weight"])

    return pd.Series(
        {
            "weighted_assessment_aps": weighted_score,
            "individual_assessment_band": assign_aps_band(weighted_score),
            "n_recent_scores_used": len(recent),
            "latest_assessment_date": recent["timestamp"].max(),
            "weights_used": ", ".join(str(round(w, 3)) for w in weights),
            "raw_attempt_aps_used": ", ".join(
                str(round(v, 1)) for v in recent["APS"]
            ),
        }
    )


