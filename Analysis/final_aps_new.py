# ============================================================
# 7. MAIN ORCHESTRATOR
# ============================================================


def run_aps_scoring(
    df: Optional[pd.DataFrame] = None,
    config: Optional[APSConfig] = None,
) -> Dict[str, object]:
    """
    Run full APS scoring pipeline.

    Returns a dictionary containing:
        df
        scoring_input
        benchmark_base
        benchmark_source
        benchmark_table
        scoring_df
        assessment_recent_scores
        category_scores
        final_aps
        final_dashboard_scores
        diagnostics
        player_cols
    """
    config = config or APSConfig()

    if df is None:
        raw_df = load_training_data(config.file_name, config.raw_columns)
    else:
        raw_df = df.copy()

    processed_df = preprocess_training_data(raw_df, config)
    player_cols = get_player_cols(processed_df)

    processed_df["aps_category"] = processed_df["category_assessment"].apply(map_assessment_category)
    scoring_input = prepare_scoring_input(processed_df)

    benchmark_base = build_benchmark_base(
        scoring_input=scoring_input,
        player_cols=player_cols,
        min_cohort_n=config.min_cohort_n,
    )

    benchmark_source = build_benchmark_source(benchmark_base)
    benchmark_table = build_benchmark_table(
        benchmark_source=benchmark_source,
        benchmark_quantiles=config.benchmark_quantiles,
    )

    scoring_df = merge_benchmarks_to_attempts(
        scoring_input=scoring_input,
        benchmark_base=benchmark_base,
        benchmark_table=benchmark_table,
        player_cols=player_cols,
    )

    scoring_df = calculate_attempt_aps(scoring_df)
    assessment_recent_scores = calculate_assessment_scores(scoring_df, player_cols)
    category_scores = calculate_category_scores(assessment_recent_scores, player_cols)
    final_aps, final_dashboard_scores = calculate_final_aps(category_scores, player_cols)

    diagnostics = build_diagnostics(
        raw_df=processed_df,
        scoring_df=scoring_df,
        benchmark_base=benchmark_base,
        benchmark_table=benchmark_table,
        assessment_recent_scores=assessment_recent_scores,
        category_scores=category_scores,
        final_aps=final_aps,
        final_dashboard_scores=final_dashboard_scores,
        player_cols=player_cols,
    )

    return {
        "df": processed_df,
        "scoring_input": scoring_input,
        "benchmark_base": benchmark_base,
        "benchmark_source": benchmark_source,
        "benchmark_table": benchmark_table,
        "scoring_df": scoring_df,
        "assessment_recent_scores": assessment_recent_scores,
        "category_scores": category_scores,
        "final_aps": final_aps,
        "final_dashboard_scores": final_dashboard_scores,
        "diagnostics": diagnostics,
        "player_cols": player_cols,
    }


