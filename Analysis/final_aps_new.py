def prepare_scoring_input(df: pd.DataFrame) -> pd.DataFrame:
    """Add APS category and exclude unmapped assessments from scoring input."""
    data = df.copy()
    data["aps_category"] = data["category_assessment"].apply(map_assessment_category)

    scoring_input = (
        data.dropna(subset=["score", "timestamp", "category_assessment", "cohort", "age_group"])
        .query("aps_category != 'Unmapped'")
        .copy()
    )

    return scoring_input


def build_benchmark_base(
    scoring_input: pd.DataFrame,
    player_cols: List[str],
    min_cohort_n: int,
) -> pd.DataFrame:
    """
    Build benchmark base using each player's most recent attempt per assessment.

    Small sample logic:
        If age-gender cohort has fewer than min_cohort_n players, use same age group
        across gender as the benchmark cohort.
    """
    benchmark_base = (
        scoring_input.sort_values("timestamp")
        .drop_duplicates(subset=player_cols + ["category_assessment"], keep="last")
        .copy()
    )

    cohort_sizes = (
        benchmark_base.groupby(["category_assessment", "cohort"])
        .size()
        .reset_index(name="n_original_cohort")
    )

    benchmark_base = benchmark_base.merge(
        cohort_sizes,
        on=["category_assessment", "cohort"],
        how="left",
    )

    benchmark_base["combined_for_small_sample"] = (
        benchmark_base["n_original_cohort"] < min_cohort_n
    )

    benchmark_base["benchmark_type"] = np.where(
        benchmark_base["combined_for_small_sample"],
        "age_group",
        "age_gender",
    )

    benchmark_base["aps_distribution_used"] = np.where(
        benchmark_base["combined_for_small_sample"],
        "Combined with same age group across gender",
        "Original age-gender cohort",
    )

    benchmark_base["benchmark_cohort"] = np.where(
        benchmark_base["benchmark_type"] == "age_group",
        benchmark_base["age_group"].astype(str),
        benchmark_base["cohort"],
    )

    return benchmark_base


def build_benchmark_source(benchmark_base: pd.DataFrame) -> pd.DataFrame:
    """Create both age-gender and age-only benchmark distributions."""
    age_gender_source = benchmark_base.copy()
    age_gender_source["benchmark_cohort"] = age_gender_source["cohort"]

    age_source = benchmark_base.copy()
    age_source["benchmark_cohort"] = age_source["age_group"].astype(str)

    return pd.concat([age_gender_source, age_source], ignore_index=True)


def build_benchmark_table(
    benchmark_source: pd.DataFrame,
    benchmark_quantiles: List[float],
) -> pd.DataFrame:
    """Build benchmark quantile table and sample sizes."""
    benchmark_table = (
        benchmark_source.groupby(["category_assessment", "benchmark_cohort"])["score"]
        .quantile(benchmark_quantiles)
        .unstack()
        .reset_index()
    )

    benchmark_table.columns = [
        "category_assessment",
        "benchmark_cohort",
        "q30",
        "q50",
        "q70",
        "q90",
    ]

    benchmark_sample_sizes = (
        benchmark_source.groupby(["category_assessment", "benchmark_cohort"])
        .size()
        .reset_index(name="n_benchmark_distribution")
    )

    benchmark_table = benchmark_table.merge(
        benchmark_sample_sizes,
        on=["category_assessment", "benchmark_cohort"],
        how="left",
    )

    return benchmark_table


def merge_benchmarks_to_attempts(
    scoring_input: pd.DataFrame,
    benchmark_base: pd.DataFrame,
    benchmark_table: pd.DataFrame,
    player_cols: List[str],
) -> pd.DataFrame:
    """Attach benchmark metadata and quantiles to every valid scoring attempt."""
    benchmark_lookup_cols = player_cols + [
        "category_assessment",
        "n_original_cohort",
        "combined_for_small_sample",
        "benchmark_type",
        "aps_distribution_used",
        "benchmark_cohort",
    ]

    benchmark_lookup = benchmark_base[benchmark_lookup_cols].drop_duplicates()

    scoring_df = scoring_input.merge(
        benchmark_lookup,
        on=player_cols + ["category_assessment"],
        how="left",
    )

    scoring_df = scoring_df.merge(
        benchmark_table,
        on=["category_assessment", "benchmark_cohort"],
        how="left",
    )

    return scoring_df


