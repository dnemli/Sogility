"""
APS Scoring System
==================

This script builds the Absolute Performance Score (APS) system for Sogility data.

Core logic
----------
1. Load and preprocess raw training session data.
2. Create age groups, clean gender, and define age-gender cohorts.
3. Exclude unmapped assessments from scoring, while keeping an audit table.
4. Build APS benchmarks using each player's most recent attempt per assessment.
5. Handle small cohort sample sizes by dropping gender and combining within age group.
6. Score every valid raw attempt using APS benchmark interpolation.
7. Calculate recency-weighted assessment APS.
8. Calculate category-level APS.
9. Calculate final overall APS.
10. Return dashboard-ready tables and diagnostics.

Important
---------
Log transformations are applied inside preprocessing. Do not apply them before running
this script unless you intentionally remove the log-transform step here.
"""

